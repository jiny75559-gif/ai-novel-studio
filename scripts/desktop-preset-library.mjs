import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
const browser = await chromium.connectOverCDP('http://127.0.0.1:9223');
const page = browser.contexts()[0].pages()[0];
const api = (name, args = {}) => page.evaluate(
  ({ name, args }) => window.__TAURI_INTERNALS__.invoke(name, args), { name, args });
assert.ok((await api('app_info')).dataDir.replaceAll('\\', '/').endsWith('/work/qa-ui/data'));
const human = JSON.parse(await readFile('../../work/qa-ui/human-workflow.json', 'utf8'));
const load = () => api('load_project', { projectId: human.pid });
const original = (await load()).writingPreset;
const nav = name => page.getByRole('button', { name, exact: true }).first().click();
const dialog = () => page.getByRole('dialog').last();
const checks = []; const check = s => { checks.push(s); console.log('PASS', s); };
await nav('我的作品');
await page.getByLabel('搜索作品', { exact: true }).fill(human.title);
await page.locator('.project-card').filter({ has: page.getByRole('heading', { name: human.title, exact: true }) })
  .getByRole('button', { name: '编辑作品', exact: true }).click();
await expect(page.locator('.writer-layout')).toBeVisible();
await nav('模型与设置');
await page.getByRole('button', { name: '管理预设 / 导入酒馆', exact: true }).click();
await dialog().getByRole('button', { name: '另存副本', exact: true }).click();
const copyName = '库副本验收 ' + Date.now();
await dialog().getByLabel('预设名称', { exact: true }).fill(copyName);
await dialog().getByRole('button', { name: '保存到预设库', exact: true }).click();
await expect(dialog().locator('.preset-feedback')).toContainText('已保存到预设库');
const copy = (await api('list_writing_presets')).find(p => p.name === copyName);
assert.ok(copy && copy.id !== original.id);
assert.deepEqual((await load()).writingPreset, original);
check('另存副本并保存到库，不更改当前作品和原模板');
await dialog().getByRole('button', { name: '保存并应用', exact: true }).click();
await expect.poll(async () => (await load()).writingPreset?.id).toBe(copy.id);
await dialog().getByLabel('预设名称', { exact: true }).fill(copyName + ' 库新版');
await dialog().getByRole('button', { name: '保存到预设库', exact: true }).click();
await expect(dialog().locator('.preset-feedback')).toContainText('已保存到预设库');
assert.equal((await load()).writingPreset.name, copyName);
await dialog().getByRole('button', { name: '删除预设', exact: true }).click();
await dialog().getByRole('button', { name: '确认', exact: true }).click();
await expect.poll(async () => (await api('list_writing_presets')).some(p => p.id === copy.id)).toBe(false);
assert.equal((await load()).writingPreset.name, copyName);
check('编辑和删除库模板后，作品已应用的独立副本仍完整保留');
await dialog().getByRole('button', { name: '恢复默认写作', exact: true }).click();
await expect.poll(async () => (await load()).writingPreset).toBe(null);
await dialog().getByLabel('预设库', { exact: true }).selectOption(original.id);
await dialog().getByRole('button', { name: '保存并应用', exact: true }).click();
await expect.poll(async () => (await load()).writingPreset?.id).toBe(original.id);
assert.deepEqual((await load()).writingPreset, original);
await dialog().getByRole('button', { name: '关闭对话框', exact: true }).click();
check('恢复默认可取消作品绑定，重新选择原预设并应用后数据保持一致');
await nav('我的作品');
await writeFile('../../work/qa-ui/preset-library-results.json', JSON.stringify({ checks }, null, 2));
process.exit(0);
